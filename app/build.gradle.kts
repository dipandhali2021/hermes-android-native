    signingConfigs {
        create("shared") {
            // A committed keystore, deliberately. Android refuses to install an
            // APK over an existing package signed with a different key, and CI
            // generates a fresh debug keystore on every run — which would force
            // an uninstall (losing app state) for every single update. This key
            // is not a secret: it signs sideloadable builds only, never a Play
            // Store upload, and every credential in the app is runtime config.
            storeFile = rootProject.file("keystore/hermes-native.jks")
            storePassword = "hermesnative"
            keyAlias = "hermes-native"
            keyPassword = "hermesnative"
        }
    }

